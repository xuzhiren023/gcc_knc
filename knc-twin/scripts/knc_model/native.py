CALLEE_SAVED = ("rbx", "rbp", "r12", "r13", "r14", "r15")
MAX_IMAGE_BYTES = 32 << 20   # the driver embeds the image as a C initializer (about 5 bytes of source per byte); larger images are not a native request anyone would build


def _memory_image(kernel):
    blocks = []
    for i, blk in enumerate(kernel.init.get("memory", [])):
        addr = parse_int(blk["addr"], "init.memory.addr")
        if "file" in blk:
            data, _ = load_input_file(blk, kernel.dir, "init.memory[%d]" % i)
        elif "fill" in blk:
            f = blk["fill"]
            unit = encode_values({k: [f[k]] for k in f if k in ("f32", "f64", "u32", "i32", "u64", "u8")}, "fill")
            data = unit * parse_int(f.get("count", 1), "fill.count")
        else:
            data = encode_values(blk, "init.memory[%d]" % i)
        blocks.append((addr, data))
    for i, blk in enumerate(kernel.expected.get("memory", [])):
        # expected output ranges belong to the relocated image too (zero-filled unless initialized)
        addr = parse_int(blk["addr"], "expected.memory.addr")
        if "file" in blk:
            n = len(load_input_file(blk, kernel.dir, "expected.memory[%d]" % i)[0])
        elif "hex" in blk:
            n = len(bytes.fromhex(blk["hex"]))
        else:
            n = len(encode_values(blk, "expected.memory[%d]" % i))
        blocks.append((addr, bytes(n)))
    if not blocks:
        return None, 0, b""
    base = min(a for a, _ in blocks) & ~0xFFF
    end = max(a + len(d) for a, d in blocks)
    span = (end - base + 63) & ~63
    if span > MAX_IMAGE_BYTES:
        raise InvalidInput("the kernel's memory blocks span %d bytes (0x%x to 0x%x); prepare-native relocates one contiguous image of at most %d bytes. "
                           "Place the kernel's arrays near its data sections (or drop data sections it does not use) before exporting a native request." % (span, base, end, MAX_IMAGE_BYTES))
    img = bytearray(span)
    for a, d in sorted(blocks, key=lambda t: 1 if any(t[1]) else 0):
        img[a - base:a - base + len(d)] = d
    return base, span, bytes(img)


def _reg_inits(kernel, stream):
    regs = dict(kernel.init.get("registers", {}))
    regs.update(stream.init.get("registers", {}))
    return regs


def gen_kernel_asm(kernel, mem_base, mem_span):
    out = []
    out.append("# Generated by knc-twin %s for native measurement. Review before building." % ENGINE_VERSION)
    out.append("# Kernel: %s. Memory image of %d bytes is relocated to knc_twin_mem (4 KiB aligned);" % (kernel.name, mem_span))
    out.append("# low 12 address bits are preserved, so L1/L2 set mapping matches the model within a page.")
    out.append("\t.text")
    zmm_tables = []
    for stream in kernel.streams:
        fn = "knc_twin_kernel_ctx%d" % stream.context
        regs = _reg_inits(kernel, stream)
        uses_stack = any("rsp" in insn.writes for insn in stream.insns)
        if uses_stack:
            out.append("# NOTE: the region adjusts rsp (push/pop/sub): the driver's own stack is used, so rsp/rbp from the kernel's init are not loaded.")
        out.append("\t.globl %s" % fn)
        out.append("\t.p2align 6")
        out.append("%s:" % fn)
        for r in CALLEE_SAVED:
            out.append("\tpushq %%%s" % r)
        # mask registers first (uses r11 as scratch), then zmm, then gprs
        for name, val in regs.items():
            n = name.lower()
            if n.startswith("k") and n[1:].isdigit():
                out.append("\tmovl $0x%x, %%r11d" % (parse_int(val, name) & 0xFFFF))
                out.append("\tkmov %%r11d, %%%s" % n)
        for name, val in regs.items():
            n = name.lower()
            if n.startswith("zmm"):
                idx = len(zmm_tables)
                zmm_tables.append(("ctx%d_%s" % (stream.context, n), zmm_from_spec(val, name)))
                out.append("\tvmovaps knc_twin_zmm_init+%d(%%rip), %%%s" % (64 * idx, n))
        for name, val in regs.items():
            n = name.lower()
            if n in GPR64 and n not in ("rsp", "rbp"):
                v = parse_int(val, name)
                if mem_base is not None and mem_base <= v < mem_base + mem_span:
                    out.append("\tleaq knc_twin_mem+%d(%%rip), %%%s" % (v - mem_base, n))
                else:
                    out.append("\tmovabsq $0x%x, %%%s" % (v & 0xFFFFFFFFFFFFFFFF, n))
        out.append("# ---- kernel body (context %d) ----" % stream.context)
        def relocate_memory(insn, addr):
            if mem_base is None or not (mem_base <= addr < mem_base + mem_span):
                raise InvalidInput("instruction %s absolute memory address 0x%x lies outside the initialized memory image" % (insn.id, addr))
            return addr - mem_base

        body = emit_gas(stream, relocate=relocate_memory)
        for line in body.splitlines():
            if line.endswith(":"):
                out.append("%s_%s" % (fn, line))  # make labels unique per function
            else:
                # rewrite branch targets to the prefixed labels
                toks = line.split()
                if toks and toks[0].startswith("j") and len(toks) >= 2:
                    toks[-1] = "%s_%s" % (fn, toks[-1])
                    out.append("\t" + " ".join(toks))
                else:
                    out.append(line)
        out.append("# ---- save architectural state for the correctness check ----")
        base = 2048 * stream.context
        for i in range(32):
            out.append("\tvmovaps %%zmm%d, knc_twin_zmm_out+%d(%%rip)" % (i, base + 64 * i))
        gbase = 128 * stream.context
        for i, r in enumerate(GPR64):
            out.append("\tmovq %%%s, knc_twin_gpr_out+%d(%%rip)" % (r, gbase + 8 * i))
        kbase = 32 * stream.context
        for i in range(8):
            out.append("\tkmov %%k%d, %%eax" % i)
            out.append("\tmovl %%eax, knc_twin_k_out+%d(%%rip)" % (kbase + 4 * i))
        for r in reversed(CALLEE_SAVED):
            out.append("\tpopq %%%s" % r)
        out.append("\tret")
        out.append("")
    out.append("\t.data")
    out.append("\t.p2align 6")
    out.append("\t.globl knc_twin_zmm_init")
    out.append("knc_twin_zmm_init:")
    for name, lanes in zmm_tables:
        out.append("\t# %s" % name)
        out.append("\t.long " + ", ".join("0x%08x" % l for l in lanes))
    if not zmm_tables:
        out.append("\t.zero 64")
    out.append("\t.bss")
    out.append("\t.p2align 12")
    out.append("\t.globl knc_twin_mem")
    out.append("knc_twin_mem:")
    out.append("\t.zero %d" % max(64, mem_span))
    out.append("\t.p2align 6")
    out.append("\t.globl knc_twin_zmm_out")
    slots = max(s.context for s in kernel.streams) + 1
    out.append("knc_twin_zmm_out:\n\t.zero %d" % (2048 * slots))
    out.append("\t.globl knc_twin_gpr_out")
    out.append("knc_twin_gpr_out:\n\t.zero %d" % (128 * slots))
    out.append("\t.globl knc_twin_k_out")
    out.append("knc_twin_k_out:\n\t.zero %d" % (32 * slots))
    out.append('\t.section .note.GNU-stack,"",@progbits')
    return "\n".join(out) + "\n"


DRIVER_C = r'''/* Generated by knc-twin %(version)s. Native measurement driver skeleton for the k1om toolchain.
 * Build (native):  k1om-mpss-linux-gcc -O2 -pthread -o knc_twin_native driver.c kernel.S
 * Run on the card: ./knc_twin_native --reps 1000 --cpus 1,2,3,4
 *   --cpus lists one CPU per context in context order (siblings of one core for a 1-4 thread test).
 *   Output: one JSON line per group/thread with TSC ticks per call, then a summary line.
 * The correctness check runs context 0..N once from the initial memory image and compares
 * the saved architectural state with the expected values from request.json. Timing repeats
 * run the kernel on its own output (memory is not restored between calls). Read README.md.
 */
#define _GNU_SOURCE
#include <pthread.h>
#include <sched.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

%(externs)s
extern unsigned char knc_twin_mem[];
extern unsigned char knc_twin_zmm_out[];
extern unsigned char knc_twin_gpr_out[];
extern unsigned char knc_twin_k_out[];

static const unsigned char mem_init[] = { %(mem_init)s };
static const size_t mem_init_size = %(mem_size)d;

typedef struct { int ctx; unsigned reg; unsigned off; unsigned len; const unsigned char *want; } expect_t;
%(expect_data)s
static const expect_t expects[] = { %(expect_entries)s };
static const int n_expects = %(n_expects)d;

typedef void (*kfn)(void);
static kfn kernels[] = { %(kernels)s };
static const int context_ids[] = { %(context_ids)s };
static const int n_ctx = %(n_ctx)d;
static const int unit_count = %(unit_count)d;
static uint64_t shared_start, finish_ticks[%(n_ctx)d];
static uint64_t envelope_samples[21];

static inline uint64_t rdtsc(void) { uint32_t lo, hi; __asm__ __volatile__("rdtsc" : "=a"(lo), "=d"(hi)); return ((uint64_t)hi << 32) | lo; }

static int cmpu64(const void *a, const void *b) { uint64_t x = *(const uint64_t *)a, y = *(const uint64_t *)b; return x < y ? -1 : x > y; }
static int cmpdouble(const void *a, const void *b) { double x = *(const double *)a, y = *(const double *)b; return x < y ? -1 : x > y; }

typedef struct { int ctx; int cpu; long reps; pthread_barrier_t *bar; double median_ticks; } targ_t;

static void *worker(void *p) {
    targ_t *t = (targ_t *)p;
    cpu_set_t set; CPU_ZERO(&set); CPU_SET(t->cpu, &set);
    if (sched_setaffinity(0, sizeof set, &set)) { perror("sched_setaffinity"); exit(2); }
    uint64_t samples[21];
    for (int w = 0; w < 3; w++) {
        pthread_barrier_wait(t->bar);
        for (long r = 0; r < t->reps; r++) kernels[t->ctx]();
        __asm__ __volatile__("mfence" ::: "memory");
        pthread_barrier_wait(t->bar);
    }
    for (int b = 0; b < 21; b++) {
        pthread_barrier_wait(t->bar);
        if (t->ctx == 0) shared_start = rdtsc();
        pthread_barrier_wait(t->bar);
        uint64_t t0 = rdtsc();
        for (long r = 0; r < t->reps; r++) kernels[t->ctx]();
        __asm__ __volatile__("mfence" ::: "memory");
        samples[b] = rdtsc() - t0;
        finish_ticks[t->ctx] = rdtsc();
        pthread_barrier_wait(t->bar);
        if (t->ctx == 0) {
            uint64_t end = finish_ticks[0];
            for (int c = 1; c < n_ctx; c++) if (finish_ticks[c] > end) end = finish_ticks[c];
            envelope_samples[b] = end - shared_start;
        }
        pthread_barrier_wait(t->bar);
    }
    qsort(samples, 21, sizeof samples[0], cmpu64);
    t->median_ticks = (double)samples[10] / (double)t->reps;
    return NULL;
}

int main(int argc, char **argv) {
    long reps = 1000; const char *cpus = NULL;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--reps") && i + 1 < argc) reps = atol(argv[++i]);
        else if (!strcmp(argv[i], "--cpus") && i + 1 < argc) cpus = argv[++i];
    }
    int cpu[CPU_SETSIZE]; int ncpu = 0;
    cpu_set_t allowed; CPU_ZERO(&allowed);
    if (sched_getaffinity(0, sizeof allowed, &allowed)) { perror("sched_getaffinity"); return 2; }
    if (reps < 1) { fprintf(stderr, "reps must be positive\n"); return 2; }
    if (cpus) {
        char *buf = strdup(cpus);
        for (char *tok = strtok(buf, ","); tok; tok = strtok(NULL, ",")) {
            char *end; long value = strtol(tok, &end, 10);
            if (*end || value < 0 || value >= CPU_SETSIZE || !CPU_ISSET(value, &allowed) || ncpu >= CPU_SETSIZE) {
                fprintf(stderr, "invalid or unavailable CPU: %%s\n", tok); free(buf); return 2;
            }
            for (int c = 0; c < ncpu; c++) if (cpu[c] == value) { fprintf(stderr, "duplicate CPU\n"); free(buf); return 2; }
            cpu[ncpu++] = (int)value;
        }
        free(buf);
    } else {
        for (int c = 0; c < CPU_SETSIZE; c++) if (CPU_ISSET(c, &allowed)) cpu[ncpu++] = c;
    }
    if (ncpu != n_ctx) { fprintf(stderr, "need exactly %%d CPUs, one worker per supplied CPU (got %%d)\n", n_ctx, ncpu); return 2; }
    /* correctness check: contexts one after another, as the model executes them */
    memset(knc_twin_mem, 0, mem_init_size); memcpy(knc_twin_mem, mem_init, mem_init_size);
    for (int c = 0; c < n_ctx; c++) kernels[c]();
    int bad = 0;
    for (int i = 0; i < n_expects; i++) {
        const expect_t *e = &expects[i]; const unsigned char *got;
        if (e->reg == 0xFFFF) got = knc_twin_mem + e->off;
        else if (e->reg < 32) got = knc_twin_zmm_out + 2048 * e->ctx + 64 * e->reg + e->off;
        else if (e->reg < 48) got = knc_twin_gpr_out + 128 * e->ctx + 8 * (e->reg - 32);
        else got = knc_twin_k_out + 32 * e->ctx + 4 * (e->reg - 48);
        if (memcmp(got, e->want, e->len)) { bad++; printf("{\"check\":\"mismatch\",\"ctx\":%%d,\"reg\":%%u,\"off\":%%u}\n", e->ctx, e->reg, e->off); }
    }
    printf("{\"check\":\"%%s\",\"expects\":%%d,\"mismatches\":%%d}\n", bad ? "mismatch" : (n_expects ? "ok" : "not_specified"), n_expects, bad);
    double group_medians[5];
    for (int g = 0; g < 5; g++) {
        pthread_barrier_t bar; pthread_barrier_init(&bar, NULL, n_ctx);
        pthread_t th[%(n_ctx)d]; targ_t ta[%(n_ctx)d];
        for (int c = 0; c < n_ctx; c++) { ta[c].ctx = c; ta[c].cpu = cpu[c]; ta[c].reps = reps; ta[c].bar = &bar; if (pthread_create(&th[c], NULL, worker, &ta[c])) { fprintf(stderr, "pthread_create failed\n"); exit(2); } }
        double worst = 0;
        for (int c = 0; c < n_ctx; c++) { pthread_join(th[c], NULL); if (ta[c].median_ticks > worst) worst = ta[c].median_ticks;
            printf("{\"group\":%%d,\"ctx\":%%d,\"cpu\":%%d,\"ticks_per_call\":%%.3f,\"ticks_per_unit\":%%.3f}\n", g, context_ids[c], ta[c].cpu, ta[c].median_ticks, ta[c].median_ticks / unit_count); }
        qsort(envelope_samples, 21, sizeof envelope_samples[0], cmpu64);
        group_medians[g] = (double)envelope_samples[10] / reps;
        printf("{\"group\":%%d,\"completion_envelope_ticks_per_call\":%%.3f,\"worst_thread_median\":%%.3f}\n", g, group_medians[g], worst);
        pthread_barrier_destroy(&bar);
    }
    qsort(group_medians, 5, sizeof(double), cmpdouble);
    double lo = group_medians[0], hi = group_medians[4], med = group_medians[2];
    printf("{\"summary\":{\"threads\":%%d,\"reps\":%%ld,\"median_ticks_per_call\":%%.3f,\"median_ticks_per_unit\":%%.3f,\"spread_pct\":%%.3f}}\n", n_ctx, reps, med, med / unit_count, 100.0 * (hi - lo) / med);
    return bad ? 6 : 0;
}
'''


def _expect_entries(kernel):
    """C initializers for the expected-state table."""
    data_lines = []
    entries = []
    k = 0

    def add(ctx, reg, off, data):
        nonlocal k
        name = "want%d" % k
        k += 1
        data_lines.append("static const unsigned char %s[] = { %s };" % (name, ", ".join("0x%02x" % b for b in data)))
        entries.append("{ %d, %d, %d, %d, %s }" % (ctx, reg, off, len(data), name))
    for stream in kernel.streams:
        exp = dict(kernel.expected.get("registers", {}).get(str(stream.context), {}))
        exp.update(stream.expected.get("registers", {}))
        for name, want in exp.items():
            n = name.lower()
            if n.startswith("zmm"):
                if isinstance(want, dict) and any(x.endswith("_broadcast") for x in want):
                    lanes = zmm_from_spec(want, name)
                    data = struct.pack("<16I", *lanes)
                else:
                    data = encode_values(want, name)
                add(stream.context, int(n[3:]), 0, data)
            elif n in GPR64:
                add(stream.context, 32 + GPR64.index(n), 0, struct.pack("<Q", parse_int(want, name) & 0xFFFFFFFFFFFFFFFF))
            elif n.startswith("k") and n[1:].isdigit():
                add(stream.context, 48 + int(n[1:]), 0, struct.pack("<I", parse_int(want, name) & 0xFFFF))
    return data_lines, entries


def prepare_native(kernel, profile, out_dir, kernel_hash, prediction_path=None):
    mem_base, mem_span, img = _memory_image(kernel)
    asm_text = gen_kernel_asm(kernel, mem_base, mem_span)
    data_lines, entries = _expect_entries(kernel)
    for i, blk in enumerate(kernel.expected.get("memory", [])):
        addr = parse_int(blk["addr"], "expected.memory.addr")
        if mem_base is None or not (mem_base <= addr < mem_base + mem_span):
            raise InvalidInput("expected.memory[%d] at 0x%x lies outside the initialized memory image; prepare-native cannot relocate it" % (i, addr))
        if "file" in blk:
            data = load_input_file(blk, kernel.dir, "expected.memory[%d]" % i)[0]
        elif "hex" in blk:
            data = bytes.fromhex(blk["hex"])
        else:
            data = encode_values(blk, "expected.memory[%d]" % i)
        name = "wantm%d" % i
        data_lines.append("static const unsigned char %s[] = { %s };" % (name, ", ".join("0x%02x" % b for b in data)))
        entries.append("{ 0, 0xFFFF, %d, %d, %s }" % (addr - mem_base, len(data), name))
    externs = "\n".join("extern void knc_twin_kernel_ctx%d(void);" % s.context for s in kernel.streams)
    driver = DRIVER_C % {
        "version": ENGINE_VERSION,
        "externs": externs,
        "mem_init": ", ".join("0x%02x" % b for b in img) if img else "0",
        "mem_size": len(img),
        "expect_data": "\n".join(data_lines),
        "expect_entries": ", ".join(entries) if entries else "{0,0,0,0,0}",
        "n_expects": len(entries),
        "kernels": ", ".join("knc_twin_kernel_ctx%d" % s.context for s in kernel.streams),
        "context_ids": ", ".join(str(s.context) for s in kernel.streams),
        "n_ctx": len(kernel.streams),
        "unit_count": kernel.unit_count,
    }
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "kernel.S"), "w", encoding="utf-8", newline="\n") as f:
        f.write(asm_text)
    with open(os.path.join(out_dir, "driver.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write(driver)
    request = {
        "schema": NATIVE_REQUEST_SCHEMA,
        "created_utc": utc_now_iso(),
        "engine_version": ENGINE_VERSION,
        "kernel_name": kernel.name,
        "kernel_hash_sha256": kernel_hash,
        "kernel": kernel.raw,
        "profile": {"id": profile.id, "version": profile.version, "hash": profile.hash},
        "prediction_result": os.path.abspath(prediction_path) if prediction_path else None,
        "unit_of_work": kernel.unit_of_work,
        "requested_measurements": [
            {"threads_per_core": t, "metric": "tsc_ticks_per_unit_per_thread", "groups": 5, "batches_per_group": 21, "warmup_batches": 3,
             "accept_if_spread_pct_below": 2.0, "placement": "siblings of one core, pinned, no other job on the card"}
            for t in (1, 2, 4) if t <= 4 and (t == 1 or len(kernel.streams) >= 1)],
        "files": {"kernel.S": "generated assembly (review; build with k1om-mpss-linux-gcc)", "driver.c": "generated driver skeleton"},
        "notes": [
            "This request needs no live connection. Submit it to the shared hardware queue (gcc_knc: tools/card_run) in a lead-only benchmark window.",
            "The driver's correctness check compares saved registers/memory to the kernel's expected values; its exit code is 6 on mismatch.",
            "Record the card_run job id, the clock policy and the MPSS version in the measurement file.",
            "Import the measurement with: knc_twin.py import-native measurement.json --request request.json --out <dir>",
        ],
    }
    if kernel.multicore:
        request["requested_measurements"] = [{
            "threads": len(kernel.streams), "metric": "completion_envelope_ticks_per_call",
            "groups": 5, "batches_per_group": 21, "warmup_batches": 3,
            "accept_if_spread_pct_below": 2.0,
            "placement": "explicit --cpus list in stream order, or exactly the granted sched_getaffinity set",
            "streams": [{"worker": i, "core": s.core, "context": s.local_context,
                         "state_slot": s.context} for i, s in enumerate(kernel.streams)],
        }]
        request["notes"].extend([
            "Multicore envelope includes the shared-start barrier and ends after all worker completion fences; report start skew separately when comparing a different driver.",
            "One worker per supplied CPU; no implicit replication of a four-context kernel. Generate matching streams for 1/2/4/8/16/30/60 cores and each sibling count.",
            "Repeated calls retain data in cache. Cold-memory and remote-owner experiments require explicit cache/ownership preconditioning by the queue operator; this skeleton does not implement handoffs.",
            "Multicore envelope rows are not core latency measurements; do not import them as core profile parameters.",
        ])
    request["request_hash_sha256"] = sha256_of_obj({k: v for k, v in request.items() if k != "created_utc"})
    dump_json(request, os.path.join(out_dir, "request.json"))
    readme = """# knc-twin native request: %s

Generated %s by knc-twin %s. No card was contacted.

Files: request.json (the reproducible request), kernel.S (assembly of the normalized records,
with register/memory setup and state save), driver.c (timing and correctness driver skeleton).

Procedure for the queue operator:
1. Review kernel.S and driver.c. Build natively: `k1om-mpss-linux-gcc -O2 -pthread -o knc_twin_native driver.c kernel.S`.
2. Run in an exclusive window with exactly one CPU per generated stream, in stream order:
   `./knc_twin_native --reps 1000 --cpus CPU0,CPU1,...`. Without `--cpus`, every granted
   CPU from `sched_getaffinity` is used and the count must equal the generated stream count.
   Single-core requests use pinned siblings; multicore requests state their placement separately.
   The envelope includes the release barrier and all completion fences. Repeated calls retain
   cache state; a cold-memory or remote-owner measurement needs operator preconditioning.
3. Fill measurement.json (schema %s) with the summary lines, job id, date, clock policy;
   list parameters only if the kernel is a calibration microbenchmark whose result isolates them.
4. `python knc_twin.py import-native measurement.json --request request.json --out <dir>`.
""" % (kernel.name, request["created_utc"], ENGINE_VERSION, NATIVE_MEASUREMENT_SCHEMA)
    with open(os.path.join(out_dir, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme)
    return request


def import_native(measurement_path, request_path, out_dir, prediction_path=None):
    m = load_json(measurement_path, "measurement")
    if m.get("schema") != NATIVE_MEASUREMENT_SCHEMA:
        raise InvalidInput("measurement schema must be %r" % NATIVE_MEASUREMENT_SCHEMA)
    for key in ("job_id", "measured_utc", "card_profile", "results"):
        if key not in m:
            raise InvalidInput("measurement is missing %r" % key)
    if not isinstance(m["results"], list) or not m["results"]:
        raise InvalidInput("measurement.results must be a non-empty list")
    kind = m.get("kind", "timing")
    if kind not in ("timing", "scatter", "rcp23-table"):
        raise InvalidInput("unknown native measurement kind %r" % kind)
    table_imports = []
    if kind == "scatter":
        from .reciprocal_tables import scatter_parameter
        params = [scatter_parameter(r) for r in m["results"]]
        if len(params) != 1:
            raise InvalidInput("scatter import needs one isolated per-line occupancy row; summarize repeats first")
        if m.get("parameters"):
            raise InvalidInput("scatter import derives its parameter from results; do not also supply parameters")
        m["parameters"] = params
    elif kind == "rcp23-table":
        from .reciprocal_tables import table_path, validate_descriptor
        seen = set()
        for row in m["results"]:
            op = row.get("op")
            if op in seen:
                raise InvalidInput("duplicate reciprocal table %s" % op)
            seen.add(op)
            file = row.get("file")
            if not isinstance(file, str):
                raise InvalidInput("reciprocal table result needs file")
            src = os.path.join(os.path.dirname(os.path.abspath(measurement_path)), file)
            name = re.sub(r"[^A-Za-z0-9_.-]", "_", str(m["job_id"])) + "-" + str(op) + ".bin"
            desc = {"file": name, "entries": row.get("entries"), "status": "synthetic" if m.get("synthetic") is True else "measured",
                    "exponent_scaling_verified": row.get("exponent_scaling_verified"),
                    "source": "native capture %s (%s) on %s" % (m["job_id"], m["measured_utc"], m["card_profile"])}
            validate_descriptor(op, desc)
            try:
                if os.path.getsize(src) != desc["entries"] * 4:
                    raise InvalidInput("%s capture byte length does not match entries" % op)
            except OSError as e:
                raise InvalidInput("cannot read capture %s: %s" % (src, e))
            table_imports.append((op, src, table_path(name), desc))
    for i, r in enumerate(m["results"]):
        for key in (("threads_per_core", "ticks_per_unit_per_thread") if kind == "timing" else ()):
            if key not in r:
                raise InvalidInput("results[%d] needs %r" % (i, key))
    req = None
    if request_path:
        req = load_json(request_path, "request")
        if req.get("schema") != NATIVE_REQUEST_SCHEMA:
            raise InvalidInput("request schema must be %r" % NATIVE_REQUEST_SCHEMA)
        if m.get("request_hash_sha256") and m["request_hash_sha256"] != req.get("request_hash_sha256"):
            raise InvalidInput("measurement.request_hash_sha256 does not match request.json; the measurement belongs to another request")
    overlay = None
    if prediction_path and kind != "timing":
        raise InvalidInput("--prediction applies to timing rows, not scatter occupancy or table captures")
    os.makedirs(out_dir, exist_ok=True)
    if m.get("parameters"):
        params = {}
        for p in m["parameters"]:
            for key in ("name", "value", "unit"):
                if key not in p:
                    raise InvalidInput("parameters entries need name, value, unit")
            params[p["name"]] = {"value": p["value"], "unit": p["unit"], "status": "measured",
                                 "source": "native measurement %s (%s) on %s%s" % (m["job_id"], m["measured_utc"], m["card_profile"], ("; " + p["note"]) if p.get("note") else ""),
                                 "uncertainty": p.get("uncertainty", "")}
        overlay = {"schema": PROFILE_SCHEMA, "id": "overlay-%s" % m["job_id"], "version": "1", "kind": "overlay", "synthetic": False,
                   "description": "Calibration overlay imported from native measurement %s" % m["job_id"],
                   "native_measurement_ids": [m["job_id"]], "parameters": params}
        dump_json(overlay, os.path.join(out_dir, "overlay-profile.json"))
    comparison = None
    if prediction_path:
        pred = load_json(prediction_path, "prediction result")
        pc = (pred.get("prediction") or {}).get("predicted_cycles_per_unit")
        if pc is not None:
            rows = []
            for r in m["results"]:
                meas = float(r["ticks_per_unit_per_thread"])
                rows.append({"threads_per_core": r["threads_per_core"], "measured_ticks_per_unit_per_thread": meas,
                             "predicted_cycles_per_unit": pc, "error_pct": 100.0 * (pc - meas) / meas if meas else None,
                             "check": r.get("check")})
            comparison = {"prediction_result": os.path.abspath(prediction_path), "rows": rows,
                          "note": "ticks are TSC ticks per thread; the prediction is core cycles per unit for the simulated context count. Compare like with like (same thread count, same unit)."}
    policy = None
    if table_imports:
        policy = {"reciprocal_tables": {op: desc for op, _, _, desc in table_imports}}
        for op, src, dest, desc in table_imports:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            if os.path.abspath(src) != os.path.abspath(dest):
                shutil.copyfile(src, dest)
        dump_json(policy, os.path.join(out_dir, "numerical-policy.json"))
    return {"measurement": m, "request_hash": req.get("request_hash_sha256") if req else None,
            "overlay_written": overlay is not None, "comparison": comparison, "numerical_policy": policy}
