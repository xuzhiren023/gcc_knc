"""S9-18: how much branch hints and profile-guided optimization gain on KNC (tests/bench/pgo/).

    python tools/s9_18_pgo.py build             card: hint variants, instrumented training programs
    python tools/s9_18_pgo.py use CARD_STDOUT   card: .gcda files from train.sh's output, PGO builds,
                                                timing programs and time.sh
    python tools/s9_18_pgo.py host              x86: the same steps with the host gcc, training run
                                                through train.sh on the host; checks the checksums

Run each through tools/run.py. Variants of each kernel, all -O2 (card: -march=knc): base (GCC's
static guesses), hint (right __builtin_expect), wrong (inverted hints), pgo (-fprofile-use from a
run on the timed input mix, other seed) and pgox (-fprofile-use from a run on the other mix).
Card files go flat into .work/_shared/S9-18/ for card_run --file-list; nothing runs on the card here.
"""
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT.parent.parent if ROOT.parent.name == '.work' else ROOT
SHARED = PROJECT / '.work/_shared'
SRC = ROOT / 'tests/bench/pgo'
KERNELS = ['skewed', 'dispatch', 'calls', 'pointer']
STATIC = {'base': '0', 'hint': '1', 'wrong': '-1'}
PROFILES = {'pgo': 0, 'pgox': 1}  # variant: training input mix
VARIANTS = [*STATIC, *PROFILES]
COMMON = ['-O2', '-std=gnu11', '-Wall', '-Wextra', '-Werror']
CYG = (SHARED / 'toolchain/cygwin/bin').as_posix()
ENV = dict(os.environ, PATH=str(SHARED / 'toolchain/cygwin/bin') + os.pathsep + os.environ['PATH'])
TARGETS = {
    'card': dict(cc=[(SHARED / 'gcc-knc-16.2.0/bin/k1om-mpss-linux-gcc.exe').as_posix(), '-march=knc'],
                 out=SHARED / 'S9-18',
                 size=(SHARED / 'toolchain/cross/bin/k1om-mpss-linux-size.exe').as_posix()),
    'host': dict(cc=[CYG + '/gcc.exe'], out=ROOT / 'tests/out/s9_18', size=CYG + '/size.exe'),
}

PGO_H = r'''/* Generated by tools/s9_18_pgo.py. HINT: 0 none, 1 right, -1 inverted. */
#if HINT > 0
#define LIKELY(x) __builtin_expect(!!(x), 1)
#define UNLIKELY(x) __builtin_expect(!!(x), 0)
#elif HINT < 0
#define LIKELY(x) __builtin_expect(!!(x), 0)
#define UNLIKELY(x) __builtin_expect(!!(x), 1)
#else
#define LIKELY(x) (x)
#define UNLIKELY(x) (x)
#endif
'''

DRIVER = r'''/* Generated by tools/s9_18_pgo.py for kernel %(kernel)s.
   prog train MIX: run the first variant on input MIX (seed 7) and print its checksum.
   prog [ROUNDS [CPU [SECONDS]]]: time every variant on mix 0 (seed 1), paired and interleaved:
   each round runs every variant once, in a shuffled order, for a batch of about SECONDS sized on
   the baseline; RATIO is T(variant) / T(base) within a round. Every batch's sum is checked. */
#define _GNU_SOURCE
#include <sched.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#ifndef CLOCK_MONOTONIC_RAW
#define CLOCK_MONOTONIC_RAW CLOCK_MONOTONIC
#endif

typedef unsigned long (*kernel_fn)(const void *);
void *setup(int mix, unsigned seed);
%(decls)s
static const struct { const char *name; kernel_fn fn; } V[] = { %(table)s };
#define NV ((int)(sizeof V / sizeof V[0]))
#define KERNEL "%(kernel)s"

static double now(void)
{
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC_RAW, &t);
    return t.tv_sec + t.tv_nsec * 1e-9;
}

static unsigned long batch(kernel_fn f, const void *in, long reps, double *sec)
{
    unsigned long s = 0;
    double t = now();
    for (long i = 0; i < reps; i++)
        s += f(in);
    *sec = now() - t;
    return s;
}

static int cmp(const void *a, const void *b)
{
    double x = *(const double *)a, y = *(const double *)b;
    return (x > y) - (x < y);
}

static double median(double *v, int n)
{
    qsort(v, n, sizeof *v, cmp);
    return n %% 2 ? v[n / 2] : (v[n / 2 - 1] + v[n / 2]) / 2;
}

int main(int argc, char **argv)
{
    if (argc == 3 && !strcmp(argv[1], "train")) {
        int mix = atoi(argv[2]);
        const void *in = setup(mix, 7);
        double t;
        unsigned long s = batch(V[0].fn, in, 20, &t);
        printf("TRAIN %%s %%s mix=%%d checksum=%%lu\n", KERNEL, V[0].name, mix, s);
        return 0;
    }
    int rounds = argc > 1 ? atoi(argv[1]) : 21, cpu = argc > 2 ? atoi(argv[2]) : -1, bad = 0;
    double target = argc > 3 ? atof(argv[3]) : 0.1, t;
    if (rounds < 1 || target <= 0)
        return 2;
    if (cpu >= 0) {
        cpu_set_t set;
        CPU_ZERO(&set);
        CPU_SET(cpu, &set);
        if (sched_setaffinity(0, sizeof set, &set) || sched_getcpu() != cpu) {
            printf("RESULT %%s FAIL: cannot pin to cpu %%d\n", KERNEL, cpu);
            return 2;
        }
    }
    const void *in = setup(0, 1);
    unsigned long ref = V[0].fn(in);
    for (int v = 0; v < NV; v++) {
        unsigned long c = V[v].fn(in);
        bad += c != ref;
        printf("CHECK %%s %%s checksum=%%lu %%s\n", KERNEL, V[v].name, c, c == ref ? "ok" : "MISMATCH");
    }
    long reps = 1;
    while (batch(V[0].fn, in, reps, &t), t < target / 4 && reps < (1L << 30))
        reps *= 2;
    reps = reps * target / t > 1 ? (long)(reps * target / t) : 1;
    printf("PILOT %%s reps=%%ld cpu=%%d\n", KERNEL, reps, cpu);
    double *ms = malloc(sizeof *ms * NV * rounds), *ratio = malloc(sizeof *ratio * NV * rounds);
    unsigned seed = 12345;
    for (int r = 0; r < rounds; r++) {
        int order[NV];
        for (int v = 0; v < NV; v++)
            order[v] = v;
        for (int v = NV - 1; v > 0; v--) {
            seed = seed * 1103515245u + 12345u;
            int j = (seed >> 16) %% (v + 1), x = order[v];
            order[v] = order[j], order[j] = x;
        }
        for (int k = 0; k < NV; k++) {
            int v = order[k];
            if (batch(V[v].fn, in, reps, &t) != ref * reps) {
                bad++;
                printf("MISMATCH %%s %%s round=%%d\n", KERNEL, V[v].name, r);
            }
            ms[v * rounds + r] = t * 1e3;
        }
        for (int v = 0; v < NV; v++) {
            ratio[v * rounds + r] = ms[v * rounds + r] / ms[r];
            printf("ROUND %%s %%d %%s ms=%%.3f ratio=%%.4f\n", KERNEL, r, V[v].name,
                   ms[v * rounds + r], ratio[v * rounds + r]);
        }
    }
    for (int v = 0; v < NV; v++) {
        double *m = ms + v * rounds, *q = ratio + v * rounds;
        double med = median(m, rounds), rmed = median(q, rounds);
        printf("SUMMARY %%s %%s median_ms=%%.3f ratio_median=%%.4f ratio_min=%%.4f ratio_max=%%.4f rounds=%%d\n",
               KERNEL, V[v].name, med, rmed, q[0], q[rounds - 1], rounds);
    }
    printf("RESULT %%s %%s\n", KERNEL, bad ? "FAIL: checksum mismatch" : "ok");
    return bad != 0;
}
'''

TRAIN_SH = r'''#!/bin/sh
# Generated by tools/s9_18_pgo.py. Lead-only card program for S9-18's training runs:
#   card_run --timeout 600 --file-list .work/_shared/S9-18/train-files.txt .work/_shared/S9-18/train.sh
# then, on the host: python tools/s9_18_pgo.py use <this job's stdout file>
# Runs each instrumented program on its input mix and prints every .gcda as hex between
# "GCDA <name>" and "END" lines. Exit 0 when every program ran.
cd -- "$(dirname -- "$0")" || exit 2
status=0
rm -rf gcda
mkdir gcda || exit 2
export GCOV_PREFIX="$PWD/gcda" GCOV_PREFIX_STRIP=64
%(runs)s
for f in gcda/*.gcda; do
    [ -e "$f" ] || { echo "RESULT no .gcda written"; exit 1; }
    echo "GCDA ${f#gcda/}"
    od -An -v -tx1 "$f"
    echo "END"
done
exit $status
'''

TIME_SH = r'''#!/bin/sh
# Generated by tools/s9_18_pgo.py use. Lead-only card program for S9-18's timing:
#   card_run --benchmark --timeout 1800 --file-list .work/_shared/S9-18/time-files.txt .work/_shared/S9-18/time.sh
# One program per kernel, one thread pinned to CPU 1 (core 0, thread 0), variants base, hint,
# wrong, pgo and pgox interleaved in a shuffled order per round, batches of about 100 ms
# (ADR-0010); SUMMARY ratio_median is T(variant) / T(base). Run it in several launches.
cd -- "$(dirname -- "$0")" || exit 2
ROUNDS=${1:-21}
status=0
echo "S9-18 start: clocksource $(cat /sys/devices/system/clocksource/clocksource0/current_clocksource 2>/dev/null); $(grep -m 1 'cpu MHz' /proc/cpuinfo)"
for k in %(kernels)s; do
    ./$k.mic "$ROUNDS" 1 0.1 > $k.out 2>&1
    rc=$?
    cat $k.out
    grep -q "^RESULT $k ok" $k.out && [ $rc = 0 ] || { echo "RESULT $k UNEXPECTED: exit=$rc"; status=1; }
done
exit $status
'''


def run(*args, cwd=None):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    return subprocess.call(list(map(str, args)), env=ENV, cwd=cwd)


def must(*args, cwd=None):
    if run(*args, cwd=cwd):
        sys.exit('FAIL: ' + ' '.join(map(str, args[:3])))


def write(path, text, mode=None):
    with open(path, 'w', newline='\n') as f:
        f.write(text)
    if mode:
        path.chmod(mode)


def driver(t, kernel, tag, names):
    decls = '\n'.join('unsigned long %s(const void *);' % n for n in names)
    table = ', '.join('{ "%s", %s }' % (n.split('_', 1)[1], n) for n in names)
    c = t['obj'] / ('driver-%s-%s.c' % (kernel, tag))
    write(c, DRIVER % dict(kernel=kernel, decls=decls, table=table))
    must(*t['cc'], *COMMON, '-c', c, '-o', c.with_suffix('.o'))
    return c.with_suffix('.o')


def kernel_compile(t, kernel, variant, flags, cwd):
    """Compile NAME=<kernel>_<variant> as a .o and a .s in CWD (relative names: a profile's .gcda
    is <cwd>/<kernel>_<variant>.gcda for both the instrumented and the -fprofile-use builds)."""
    name = '%s_%s' % (kernel, variant)
    base = [*t['cc'], *COMMON, *flags, '-DNAME=' + name, '-I', t['obj'].as_posix(),
            (SRC / (kernel + '.c')).as_posix()]
    must(*base, '-c', '-o', name + '.o', cwd=cwd)
    if '-fprofile-generate' not in flags:
        must(*base, '-S', '-o', name + '.s', cwd=cwd)
    return cwd / (name + '.o')


def setup_target(which):
    t = dict(TARGETS[which])
    t['obj'], t['prof'] = t['out'] / 'obj', t['out'] / 'prof'
    for d in (t['out'], t['obj'], t['prof']):
        d.mkdir(parents=True, exist_ok=True)
    return t


def lint(t, exe):
    if 'k1om' in t['cc'][0]:
        must(sys.executable, ROOT / 'tools/knc_lint', exe)


def build(which):
    t = setup_target(which)
    write(t['obj'] / 'pgo.h', PGO_H)
    runs, staged = [], []
    for k in KERNELS:
        must(*t['cc'], *COMMON, '-DSETUP', '-DHINT=0', '-I', t['obj'].as_posix(),
             '-c', SRC / (k + '.c'), '-o', t['obj'] / (k + '-setup.o'))
        for v, hint in STATIC.items():
            kernel_compile(t, k, v, ['-DHINT=' + hint], t['obj'])
        for v, mix in PROFILES.items():
            for stale in t['prof'].glob('%s_%s.gcda' % (k, v)):
                stale.unlink()
            obj = kernel_compile(t, k, v, ['-DHINT=0', '-fprofile-generate'], t['prof'])
            exe = t['out'] / ('%s-train-%s.mic' % (k, v))
            must(*t['cc'], '-fprofile-generate', driver(t, k, 'train-' + v, [k + '_' + v]),
                 t['obj'] / (k + '-setup.o'), obj, '-o', exe)
            lint(t, exe)
            runs.append('./%s train %d || { echo "RESULT %s UNEXPECTED: exit=$?"; status=1; }'
                        % (exe.name, mix, exe.name))
            staged.append(exe)
    write(t['out'] / 'train.sh', TRAIN_SH % dict(runs='\n'.join(runs)), 0o755)
    staged.append(t['out'] / 'train.sh')
    write(t['out'] / 'train-files.txt', ''.join(rel(p) + '\n' for p in staged))
    report(t, list(STATIC))
    print('BUILT (NOT executed on card): ' + rel(t['out'] / 'train.sh'))
    return t


def rel(p):
    try:
        return Path(p).relative_to(PROJECT).as_posix()
    except ValueError:
        return Path(p).as_posix()


def parse_gcda(text):
    files, name = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('GCDA '):
            name, data = line[5:].strip(), bytearray()
        elif line == 'END' and name:
            files[name] = bytes(data)
            name = None
        elif name:
            data.extend(int(b, 16) for b in line.split() if re.fullmatch(r'[0-9a-f]{2}', b))
    return files


def use(which, stdout_file):
    t = setup_target(which)
    files = parse_gcda(Path(stdout_file).read_text(errors='replace'))
    want = ['%s_%s.gcda' % (k, v) for k in KERNELS for v in PROFILES]
    missing = [n for n in want if n not in files]
    if missing:
        sys.exit('FAIL: no profile for ' + ', '.join(missing))
    for n in want:
        if files[n][:4] not in (b'adcg', b'gcda'):
            sys.exit('FAIL: %s is not a .gcda (%d bytes)' % (n, len(files[n])))
        (t['prof'] / n).write_bytes(files[n])
        print('%s: %d bytes' % (n, len(files[n])))
    staged = []
    for k in KERNELS:
        objs = [t['obj'] / (k + '-setup.o')] + [t['obj'] / ('%s_%s.o' % (k, v)) for v in STATIC]
        for v in PROFILES:
            objs.append(kernel_compile(t, k, v, ['-DHINT=0', '-fprofile-use'], t['prof']))
        exe = t['out'] / (k + '.mic')
        must(*t['cc'], driver(t, k, 'time', ['%s_%s' % (k, v) for v in VARIANTS]), *objs, '-o', exe)
        lint(t, exe)
        staged.append(exe)
    write(t['out'] / 'time.sh', TIME_SH % dict(kernels=' '.join(KERNELS)), 0o755)
    staged.append(t['out'] / 'time.sh')
    write(t['out'] / 'time-files.txt', ''.join(rel(p) + '\n' for p in staged))
    report(t)
    print('BUILT (NOT executed on card): ' + rel(t['out'] / 'time.sh'))
    return t


def report(t, variants=VARIANTS):
    """Per kernel and variant: bytes of .text and .text.unlikely in the kernel's object, and in its
    assembly the calls, conditional jumps and .cold parts that explain the expected effects."""
    print('REPORT kernel variant text unlikely hot calls jcc cold call_targets')
    for k in KERNELS:
        for v in variants:
            d = t['prof'] if v in PROFILES else t['obj']
            name = '%s_%s' % (k, v)
            sizes = subprocess.run([t['size'], '-A', d / (name + '.o')], env=ENV, text=True,
                                   stdout=subprocess.PIPE).stdout
            sec = dict((m.group(1), int(m.group(2)))
                       for m in re.finditer(r'^(\.text\S*)\s+(\d+)', sizes, re.M))
            asm = (d / (name + '.s')).read_text()
            calls = re.findall(r'^\s+call\w*\s+(\S+)', asm, re.M)
            print('REPORT %s %s %d %d %d %d %d %d %s' % (
                k, v, sec.get('.text', 0), sec.get('.text.unlikely', 0), sec.get('.text.hot', 0),
                len(calls), len(re.findall(r'^\s+j(?!mp)\w+\s', asm, re.M)),
                len(re.findall(r'^\S+\.cold:', asm, re.M)), ','.join(sorted(set(calls))) or '-'))


def host():
    t = build('host')
    out = t['out'] / 'train.out'
    with open(out, 'w') as f:
        rc = subprocess.call([CYG + '/sh.exe', (t['out'] / 'train.sh').as_posix()], env=ENV, stdout=f)
    print('train.sh exit %d' % rc)
    if rc:
        return 1
    use('host', out)
    bad = 0
    for k in KERNELS:
        res = subprocess.run([str(t['out'] / (k + '.mic')), '3', '-1', '0.01'], env=ENV, text=True,
                             stdout=subprocess.PIPE)
        lines = [l for l in res.stdout.splitlines() if l.startswith(('CHECK', 'SUMMARY', 'RESULT'))]
        print('\n'.join(lines))
        bad += res.returncode != 0 or ('RESULT %s ok' % k) not in res.stdout
    print('HOST %s: checksums across %s' % ('FAIL' if bad else 'PASS', ', '.join(VARIANTS)))
    return 1 if bad else 0


def main():
    args = sys.argv[1:]
    if args == ['build']:
        build('card')
        return 0
    if len(args) == 2 and args[0] == 'use':
        use('card', args[1])
        return 0
    if args == ['host']:
        return host()
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main())
