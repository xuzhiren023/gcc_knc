"""S9-20: instruction scheduling on the in-order KNC core (flags only, no compiler change).

    python tools/s9_20_sched.py build   card: sched.mic (M2 + scalar kernels, five variants),
                                        sched.sh, sched-files.txt, report.txt (flags, sched2
                                        dump evidence, hot-loop spills and sizes per variant)
    python tools/s9_20_sched.py host    x86: the scalar kernels run small; outputs equal across variants

Run through tools/run.py. Card files go flat into .work/_shared/S9-20/; nothing runs on the card here.
"""
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT.parent.parent if ROOT.parent.name == '.work' else ROOT
SHARED = PROJECT / '.work/_shared'
SCHED = ROOT / 'tests/bench/sched/sched.c'
M2 = ROOT / 'tests/acceptance/m2_kernels'
CYG = (SHARED / 'toolchain/cygwin/bin').as_posix()
ENV = dict(os.environ, PATH=str(SHARED / 'toolchain/cygwin/bin') + os.pathsep + os.environ['PATH'])
PREFIX = SHARED / 'gcc-knc-16.2.0'
OUT = SHARED / 'S9-20'
KNC_CC = [(PREFIX / 'bin/k1om-mpss-linux-gcc.exe').as_posix(), '-march=knc']
COMMON = ['-O2', '-std=gnu11', '-Wall', '-Wextra', '-Werror']
# M2 kernels as the M2 'gcc' build compiles them; scalar kernels with vectorization off.
M2_FLAGS = ['-ffp-contract=fast', '-ftree-vectorize']
SCALAR_FLAGS = ['-fno-tree-vectorize', '-fno-tree-slp-vectorize']
VARIANTS = [
    ('base', []),
    ('nosched', ['-fno-schedule-insns', '-fno-schedule-insns2']),
    ('pre', ['-fschedule-insns']),
    ('prepress', ['-fschedule-insns', '-fsched-pressure']),
    ('prepress1', ['-fschedule-insns', '-fsched-pressure', '--param', 'knc-threads-per-core=1']),
]
M2_KERNELS = ['affine_f32', 'affine_f64', 'stencil1', 'stencil2', 'mat8', 'mat16']

SCHED_SH = r'''#!/bin/sh
# Generated by tools/s9_20_sched.py. Lead-only card program for S9-20's scheduling experiment:
#   card_run --benchmark --timeout 3600 --file-list .work/_shared/S9-20/sched-files.txt .work/_shared/S9-20/sched.sh
# Paired rounds (ADR-0010), see docs/research/s9-20-sched.md. SUMMARY ratio_median is
# ms(variant) / ms(base) in the same round. Four passes: M2 at L2 on all whole cores at 1 and 4
# threads per core, then the scalar kernels on one core as 1 pinned thread and as 4 copies.
cd -- "$(dirname -- "$0")" || exit 2
ROUNDS=${1:-21}
status=0
echo "S9-20 start: $(nproc) cpus; clocksource $(cat /sys/devices/system/clocksource/clocksource0/current_clocksource 2>/dev/null); $(grep -m 1 'cpu MHz' /proc/cpuinfo)"
for pass in "m2 1" "m2 4" "scalar 1" "scalar 4"; do
    set -- $pass
    echo "PASS $1 threads_per_core=$2"
    ./sched.mic $1 $2 "$ROUNDS" 0.1 > sched-$1-$2.out 2>&1
    rc=$?
    sed "s/^/$1-$2 /" sched-$1-$2.out
    grep -q "^RESULT ok" sched-$1-$2.out && [ $rc = 0 ] || { echo "RESULT $1-$2 UNEXPECTED: exit=$rc"; status=1; }
done
exit $status
'''


def must(*args):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    if subprocess.call(list(map(str, args)), env=ENV):
        sys.exit('FAIL: ' + ' '.join(map(str, args[:3])))


def capture(*args):
    p = subprocess.run(list(map(str, args)), env=ENV, text=True, errors='replace',
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if p.returncode:
        print(p.stdout[-2000:])
        sys.exit('FAIL: ' + ' '.join(map(str, args[:3])))
    return p.stdout


def functions(asm):
    """{name: [instruction or label lines]} from a GCC .s file."""
    funcs, name = {}, None
    for line in asm.splitlines():
        m = re.match(r'^([A-Za-z_]\w*):', line)
        if m:
            name = m.group(1)
            funcs[name] = []
        elif name and re.match(r'^\.L\w+:', line):
            funcs[name].append(line.strip())
        elif name and line.startswith('\t') and not line.lstrip().startswith('.'):
            funcs[name].append(line.strip())
        elif name and line.lstrip().startswith('.size'):
            name = None
    return funcs


STACK = re.compile(r'\(%(rsp|rbp)\)')


def hot_loops(body):
    """Instructions inside a backward branch's range (innermost loops and their enclosing ones)."""
    where = {l[:-1]: i for i, l in enumerate(body) if l.startswith('.L') and l.endswith(':')}
    inside = set()
    for i, l in enumerate(body):
        m = re.match(r'^j\w+\s+(\.L\w+)$', l)
        if m and where.get(m.group(1), i + 1) <= i:
            inside.update(range(where[m.group(1)] + 1, i + 1))
    return [body[i] for i in sorted(inside) if not body[i].startswith('.L')]


def loop_stats(body):
    loop = hot_loops(body)
    loads = sum(1 for l in loop if STACK.search(l) and not l.startswith('lea')
                and not re.search(r',\s*-?\d*\(%(rsp|rbp)\)$', l))
    stores = sum(1 for l in loop if re.search(r',\s*-?\d*\(%(rsp|rbp)\)$', l))
    return len(loop), loads, stores


def report_flags():
    lines = []
    for flags in ([], ['-fschedule-insns']):
        text = capture(*KNC_CC, '-O2', *flags, '-Q', '--help=optimizers')
        for opt in ('-fschedule-insns ', '-fschedule-insns2', '-fsched-pressure',
                    '-fsched-interblock', '-fsched-spec ', '-fsched2-use-superblocks'):
            hit = [l.strip() for l in text.splitlines() if l.strip().startswith(opt.strip())
                   and l.strip().split()[0] == opt.strip()]
            lines.append('FLAG -O2 -march=knc%s: %s' % (''.join(' ' + f for f in flags),
                                                        ' '.join(hit[0].split()) if hit else opt + ' ?'))
    text = capture(*KNC_CC, '-O2', '-Q', '--help=params')
    lines += ['PARAM ' + ' '.join(l.split()) for l in text.splitlines()
              if 'knc-threads-per-core' in l or 'sched-pressure-algorithm' in l]
    tune = capture(*KNC_CC, '-O2', '-Q', '--help=target')
    lines += ['TARGET ' + ' '.join(l.split()) for l in tune.splitlines()
              if re.match(r'\s+-m(arch|tune)=\s', l)]
    return lines


def report_dump(obj):
    """sched2 (and sched1 when on) dumps for the scalar FP kernel: is knc.md's automaton used?"""
    lines = []
    for name, flags in (('base', []), ('pre', ['-fschedule-insns'])):
        capture(*KNC_CC, *COMMON, *SCALAR_FLAGS, *flags, '-DV=' + name, '-fsched-verbose=4',
                '-fdump-rtl-sched1', '-fdump-rtl-sched2', '-dumpbase', 'dump-' + name,
                '-dumpdir', obj.as_posix() + '/', '-c', SCHED, '-o', obj / ('dump-' + name + '.o'))
        for kind in ('sched1', 'sched2'):
            files = list(obj.glob('dump-%s*r.%s' % (name, kind)))
            if not files:
                lines.append('DUMP %s %s: no dump file' % (name, kind))
                continue
            text = files[0].read_text(errors='replace')
            fn = text.split(';; Function x87poly_' + name)[-1]
            units = sorted(set(re.findall(r':(knc-[uv]|knc-fp)\b', fn)))
            reserv = sorted(set(re.findall(r'\bknc_\w+', fn)))
            scheduled = len(re.findall(r'^;;\s+\d+-->', fn, re.M))
            lines.append('DUMP %s %s (%s): %d scheduled-insn lines; units %s; reservations %s'
                         % (name, kind, files[0].name, scheduled, ' '.join(units) or 'none',
                            ' '.join(reserv) or 'none'))
            sample = [l for l in fn.splitlines() if re.match(r'^;;\s+\d+-->', l)][:4]
            lines += ['DUMP   ' + ' '.join(l.split()) for l in sample]
    return lines


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    obj = OUT / 'obj'
    shutil.rmtree(obj, ignore_errors=True)
    obj.mkdir(parents=True)
    report = report_flags()
    report += report_dump(obj)
    objs, stats = [], {}
    for name, flags in VARIANTS:
        for unit, src, extra in (('m2', M2 / 'kernels.c', [*M2_FLAGS, '-DBUILD=' + name]),
                                 ('scalar', SCHED, [*SCALAR_FLAGS, '-DV=' + name])):
            s = obj / ('%s-%s.s' % (unit, name))
            must(*KNC_CC, *COMMON, *extra, *flags, '-I', M2, '-S', src, '-o', s)
            must(*KNC_CC, '-c', s, '-o', s.with_suffix('.o'))
            objs.append(s.with_suffix('.o'))
            for fn, body in functions(s.read_text()).items():
                stats[(fn.rsplit('_', 1)[0], name)] = loop_stats(body)
    report.append('SPILLS hot-loop instructions / stack loads / stack stores, per kernel and variant:')
    for k in ['m2_' + k for k in M2_KERNELS] + ['ichain', 'x87poly']:
        report.append('SPILLS %-14s ' % k + '  '.join(
            '%s=%d/%d/%d' % ((v,) + stats.get((k, v), (-1, -1, -1))) for v, _ in VARIANTS))
    drv = obj / 'driver.o'
    must(*KNC_CC, *COMMON, '-DDRIVER', '-I', M2, '-c', SCHED, '-o', drv)
    exe = OUT / 'sched.mic'
    must(*KNC_CC, drv, *objs, '-pthread', '-o', exe)
    must(sys.executable, ROOT / 'tools/knc_lint', exe)
    (OUT / 'sched.sh').write_bytes(SCHED_SH.encode())
    (OUT / 'sched-files.txt').write_bytes(''.join(
        p.relative_to(PROJECT).as_posix() + '\n' for p in (exe, OUT / 'sched.sh')).encode())
    (OUT / 'report.txt').write_text('\n'.join(report) + '\n')
    print('\n'.join(report))
    print('BUILT (NOT executed on card): .work/_shared/S9-20/sched.sh')
    return 0


def host():
    """Host x86 build of the scalar kernels in all variants; the driver's checks compare outputs.
    The KNC-only flag (--param knc-threads-per-core) is dropped; pinning needs a whole 4-sibling
    core, which the host does not have, so this drives the kernels directly."""
    out = ROOT / 'tests/out/s9_20'
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    cc = [CYG + '/gcc.exe']
    objs = []
    for name, flags in VARIANTS:
        o = out / (name + '.o')
        must(*cc, *COMMON, *SCALAR_FLAGS, *[f for f in flags if 'knc' not in f and f != '--param'],
             '-DV=' + name, '-c', SCHED, '-o', o)
        objs.append(o)
    main = out / 'main.c'
    main.write_text('#include <stdio.h>\n#include <string.h>\n'
                    + ''.join('void ichain_%s(void*,const void*,const void*,unsigned long);'
                              'void x87poly_%s(void*,const void*,const void*,unsigned long);\n'
                              % (v, v) for v, _ in VARIANTS)
                    + 'typedef void (*fn)(void*,const void*,const void*,unsigned long);\n'
                    'static fn I[] = {%s}, X[] = {%s};\n' % (
                        ','.join('ichain_' + v for v, _ in VARIANTS),
                        ','.join('x87poly_' + v for v, _ in VARIANTS)) +
                    r'''int main(void) {
  long a[256], b[256], y0, y; double x[256], c[4] = {0.5, -1.25, 0.75, 0.25}, d0[257], d[257];
  int bad = 0;
  for (int i = 0; i < 256; i++) a[i] = (long)(i * 2654435761u % 1000003) - 500000,
    b[i] = i % 97 - 48, x[i] = (double)(i % 63 - 31) / 4;
  I[0](&y0, a, b, 256); X[0](d0, x, c, 256);
  for (int v = 0; v < 5; v++) {
    I[v](&y, a, b, 256); X[v](d, x, c, 256);
    int ok = y == y0 && !memcmp(d, d0, sizeof d);
    bad += !ok;
    printf("CHECK variant=%d ichain=%016lx x87poly_sum=%.17g %s\n", v, (unsigned long)y, d[256],
           ok ? "ok" : "MISMATCH");
  }
  printf("RESULT %s\n", bad ? "FAIL" : "ok");
  return bad;
}
''')
    exe = out / 'host.exe'
    must(*cc, '-O0', main, *objs, '-o', exe)
    res = subprocess.run([str(exe)], env=ENV, text=True, stdout=subprocess.PIPE)
    print(res.stdout)
    return res.returncode


if __name__ == '__main__':
    mode = {'build': build, 'host': host}.get(sys.argv[1] if len(sys.argv) == 2 else '')
    sys.exit(mode() if mode else print(__doc__) or 2)
