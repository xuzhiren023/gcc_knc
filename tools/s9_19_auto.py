"""S9-19: GCC auto-parallelization on KNC, and whether AutoFDO's perf sampling works on the card.

    python tools/s9_19_auto.py build    card: autopar.mic (tests/bench/autopar/loops.c, seven variants
                                        in one program), the opt-info report, perf_probe.mic
                                        (tests/bench/autofdo/perf_probe.c), libgomp.so.1, autopar.sh,
                                        probe.sh and their --file-lists
    python tools/s9_19_auto.py host     x86: the same autopar program with the host gcc, run small;
                                        checks every variant's checksum against the serial one

Run each through tools/run.py. Variants, all -O2 (card: -march=knc): par1, par60, par120, par240
(plain loops, -ftree-parallelize-loops=N; 1 is off) and omp60, omp120, omp240 (the same loops with
"#pragma omp parallel for num_threads(T)", -fopenmp). Card files go flat into .work/_shared/S9-19/
for card_run --file-list; nothing runs on the card here.
"""
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT.parent.parent if ROOT.parent.name == '.work' else ROOT
SHARED = PROJECT / '.work/_shared'
LOOPS = ROOT / 'tests/bench/autopar/loops.c'
PROBE = ROOT / 'tests/bench/autofdo/perf_probe.c'
PAR = [1, 60, 120, 240]
OMP = [60, 120, 240]
COMMON = ['-O2', '-std=gnu11', '-Wall', '-Wextra', '-Werror']
CYG = (SHARED / 'toolchain/cygwin/bin').as_posix()
ENV = dict(os.environ, PATH=str(SHARED / 'toolchain/cygwin/bin') + os.pathsep + os.environ['PATH'])
PREFIX = SHARED / 'gcc-knc-16.2.0'
TARGETS = {
    'card': dict(cc=[(PREFIX / 'bin/k1om-mpss-linux-gcc.exe').as_posix(), '-march=knc'],
                 out=SHARED / 'S9-19'),
    'host': dict(cc=[CYG + '/gcc.exe'], out=ROOT / 'tests/out/s9_19'),
}

AUTOPAR_SH = r'''#!/bin/sh
# Generated by tools/s9_19_auto.py. Lead-only card program for S9-19's auto-parallelization timing:
#   card_run --benchmark --timeout 1800 --file-list .work/_shared/S9-19/autopar-files.txt .work/_shared/S9-19/autopar.sh
# One program, three kernels (triad, stencil, reduce); per kernel every variant (par1 serial,
# par60/120/240 from -ftree-parallelize-loops, omp60/120/240 from omp parallel for) runs once per
# round in a shuffled order, a warm-up call then a batch of about 100 ms (ADR-0010 pairing);
# SUMMARY ratio_median is ms/call(variant) / ms/call(par1). Two passes: libgomp's default placement,
# then OMP_PROC_BIND=spread OMP_PLACES=threads. Run it in several launches.
cd -- "$(dirname -- "$0")" || exit 2
ROUNDS=${1:-11}
status=0
echo "S9-19 start: $(nproc) cpus; clocksource $(cat /sys/devices/system/clocksource/clocksource0/current_clocksource 2>/dev/null); $(grep -m 1 'cpu MHz' /proc/cpuinfo)"
for bind in default spread; do
    if [ $bind = spread ]; then export OMP_PROC_BIND=spread OMP_PLACES=threads; fi
    echo "PASS $bind OMP_PROC_BIND=${OMP_PROC_BIND-unset} OMP_PLACES=${OMP_PLACES-unset}"
    LD_LIBRARY_PATH=. ./autopar.mic "$ROUNDS" 0.1 > autopar-$bind.out 2>&1
    rc=$?
    sed "s/^/$bind /" autopar-$bind.out
    grep -q "^RESULT ok" autopar-$bind.out && [ $rc = 0 ] || { echo "RESULT $bind UNEXPECTED: exit=$rc"; status=1; }
done
exit $status
'''

PROBE_SH = r'''#!/bin/sh
# Generated by tools/s9_19_auto.py. Lead-only card program for S9-19's AutoFDO feasibility probe:
#   card_run --timeout 300 --file-list .work/_shared/S9-19/probe-files.txt .work/_shared/S9-19/probe.sh
# Reads only; changes nothing on the card.
cd -- "$(dirname -- "$0")" || exit 2
echo "KERNEL $(uname -r) $(uname -m)"
echo "PERF_BINARY $(command -v perf 2>/dev/null || echo none) $(ls /usr/bin/perf* /usr/sbin/perf* /usr/libexec/perf* 2>/dev/null | tr '\n' ' ')"
echo "PARANOID $(cat /proc/sys/kernel/perf_event_paranoid 2>&1)"
echo "MLOCK_KB $(cat /proc/sys/kernel/perf_event_mlock_kb 2>&1)"
echo "MAX_SAMPLE_RATE $(cat /proc/sys/kernel/perf_event_max_sample_rate 2>&1)"
echo "EVENT_SOURCES $(ls /sys/bus/event_source/devices/ 2>&1 | tr '\n' ' ')"
for d in /sys/bus/event_source/devices/*; do
    [ -d "$d" ] && echo "EVENT_SOURCE $(basename "$d") type=$(cat "$d/type" 2>&1) $(ls "$d" | tr '\n' ' ')"
done
echo "PMU_SYMBOLS $(grep -i -E -o '\b(knc|p6|intel)_pmu[a-z_]*' /proc/kallsyms 2>/dev/null | sort -u | tr '\n' ' ')"
echo "CPU_FLAGS $(grep -m 1 '^flags' /proc/cpuinfo)"
./perf_probe.mic
'''


def run(*args, cwd=None):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    return subprocess.call(list(map(str, args)), env=ENV, cwd=cwd)


def must(*args, cwd=None):
    if run(*args, cwd=cwd):
        sys.exit('FAIL: ' + ' '.join(map(str, args[:3])))


def capture(*args):
    p = subprocess.run(list(map(str, args)), env=ENV, text=True, errors='replace',
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if p.returncode:
        print(p.stdout[-2000:])
        sys.exit('FAIL: ' + ' '.join(map(str, args[:3])))
    return p.stdout


def write(path, text, mode=None):
    with open(path, 'w', newline='\n') as f:
        f.write(text)
    if mode:
        path.chmod(mode)


def rel(p):
    try:
        return Path(p).relative_to(PROJECT).as_posix()
    except ValueError:
        return Path(p).as_posix()


def variants():
    """(name, flags) for every variant object."""
    return ([('par%d' % n, ['-DOMP=0', '-ftree-parallelize-loops=%d' % n]) for n in PAR] +
            [('omp%d' % n, ['-DOMP=%d' % n, '-fopenmp']) for n in OMP])


def build_autopar(t):
    """Compile every variant with -fopt-info-loop-optimized, and par60 once more with the parloops
    dump, then link autopar.mic. Returns the opt-info report lines."""
    obj = t['out'] / 'obj'
    shutil.rmtree(obj, ignore_errors=True)
    obj.mkdir(parents=True)
    report, objs = [], []
    for name, flags in variants():
        o = obj / (name + '.o')
        text = capture(*t['cc'], *COMMON, *flags, '-DV=' + name, '-fopt-info-loop-optimized',
                       '-c', LOOPS, '-o', o)
        # The KNC vectorizer's candidate notes are not about parallelization; keep the rest.
        for line in text.splitlines():
            m = re.search(r'loops\.c:(\d+):\d+: optimized: (?!\s*KNC candidate)(.*)', line)
            if m:
                report.append('OPTINFO %s line %s: %s' % (name, m.group(1), m.group(2)))
        objs.append(o)
    capture(*t['cc'], *COMMON, '-DOMP=0', '-DV=par60', '-ftree-parallelize-loops=60',
            '-fdump-tree-parloops-details', '-dumpbase', 'par60', '-dumpdir', obj.as_posix() + '/',
            '-c', LOOPS, '-o', obj / 'dump.o')
    dump = next(obj.glob('par60*parloops*')).read_text(errors='replace')
    for fn in re.split(r'^;; Function ', dump, flags=re.M)[1:]:
        name = fn.split(' ', 1)[0]
        if 'loopfn' in name:  # an outlined loop body, not one of the three loops
            continue
        verdicts = re.findall(r'(parallelizing \w+ loop \d+|FAILED: [^\n]*|detected reduction: [^\n]*'
                              r'|not parallelized[^\n]*)', fn)
        report.append('PARLOOPS %s: %s' % (name, '; '.join(dict.fromkeys(verdicts)) or 'no verdict'))
    drv = obj / 'driver.o'
    must(*t['cc'], *COMMON, '-DDRIVER', '-c', LOOPS, '-o', drv)
    exe = t['out'] / 'autopar.mic'
    must(*t['cc'], '-fopenmp', drv, *objs, '-Wl,-rpath,$ORIGIN', '-o', exe)
    return exe, report


def build():
    t = dict(TARGETS['card'])
    t['out'].mkdir(parents=True, exist_ok=True)
    exe, report = build_autopar(t)
    probe = t['out'] / 'perf_probe.mic'
    must(*t['cc'], *COMMON, PROBE, '-o', probe)
    gomp = t['out'] / 'libgomp.so.1'
    # libgomp.so.1 in the prefix is a Cygwin symlink, which Windows Python cannot open.
    shutil.copyfile(PREFIX / 'k1om-mpss-linux/lib64/libgomp.so.1.0.0', gomp)
    for f in (exe, probe, gomp):
        must(sys.executable, ROOT / 'tools/knc_lint', f)
    needed = capture((SHARED / 'toolchain/cross/bin/k1om-mpss-linux-readelf.exe').as_posix(), '-d', exe)
    print('NEEDED autopar.mic: ' + ' '.join(re.findall(r'Shared library: \[([^\]]+)\]', needed)))
    write(t['out'] / 'autopar.sh', AUTOPAR_SH, 0o755)
    write(t['out'] / 'probe.sh', PROBE_SH, 0o755)
    write(t['out'] / 'autopar-files.txt', ''.join(rel(p) + '\n' for p in (exe, gomp, t['out'] / 'autopar.sh')))
    write(t['out'] / 'probe-files.txt', ''.join(rel(p) + '\n' for p in (probe, t['out'] / 'probe.sh')))
    write(t['out'] / 'optinfo.txt', '\n'.join(report) + '\n')
    print('\n'.join(report))
    print('BUILT (NOT executed on card): %s, %s' % (rel(t['out'] / 'autopar.sh'), rel(t['out'] / 'probe.sh')))
    return 0


def host():
    t = dict(TARGETS['host'])
    t['out'].mkdir(parents=True, exist_ok=True)
    exe, report = build_autopar(t)
    print('\n'.join(report))
    res = subprocess.run([str(exe), '2', '0.005', '100003'], env=ENV, text=True, stdout=subprocess.PIPE)
    print('\n'.join(l for l in res.stdout.splitlines() if l.startswith(('CHECK', 'MISMATCH', 'RESULT'))))
    ok = res.returncode == 0 and 'RESULT ok' in res.stdout
    print('HOST %s: checksums across %s' % ('PASS' if ok else 'FAIL', ', '.join(n for n, _ in variants())))
    return 0 if ok else 1


def main():
    args = sys.argv[1:]
    if args == ['build']:
        return build()
    if args == ['host']:
        return host()
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main())
